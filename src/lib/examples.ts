export function getPromptSections(selectedLayerIds: readonly string[], userRequest = defaultUserRequest): PromptSection[] {
  const selected = new Set(selectedLayerIds);
  const sections: PromptSection[] = [
    { id: "system", label: "System prompt", content: baseSystem },
  ];

  for (const layer of promptPatchLayers) {
    if (selected.has(layer.id)) {
      sections.push({
        id: layer.id,
        label: layer.id === "instructions" ? "Custom instructions" : layer.name,
        content: layer.content,
      });
    }
  }

  if (userRequest.length > 0) {
    sections.push({
      id: "user",
      label: "User message",
      content: userRequest.startsWith("<userRequest>") || userRequest.startsWith("<attachments>")
        ? userRequest
        : `<userRequest>\n${userRequest}\n</userRequest>`,
    });
  }

  return sections;
}

export function composePrompt(selectedLayerIds: readonly string[], userRequest = defaultUserRequest) {
  return getPromptSections(selectedLayerIds, userRequest)
    .map((section) => section.content)
    .join("\n\n");
}

export function composeConversationRequest(
  messages: readonly string[],
  options: { includeAssistantResponses?: boolean; omitLastAssistantResponse?: boolean } = {},
) {
  if (messages.length === 0) {
    return "";
  }

  return [
    requestEnvelope,
    ...messages.flatMap((message, index) => [
      replaceTaggedContent("<userRequest>\ntell me something new\n</userRequest>", "userRequest", message),
      ...(options.includeAssistantResponses &&
      !(options.omitLastAssistantResponse && index === messages.length - 1)
        ? [assistantResponseTraceForTurn(index)]
        : []),
    ]),
  ].join("\n\n");
}

export function createPatchDiff(layer: PromptPatchLayer) {
  const additions = layer.content.split("\n").map((line) => `+${line}`);
  return [
    `diff --git a/copilot-prompt.trace b/copilot-prompt.trace`,
    `--- a/copilot-prompt.trace`,
    `+++ b/copilot-prompt.trace`,
    `@@ insert ${layer.id} before <userRequest> @@`,
    ...additions,
  ].join("\n");
}

function extractTaggedContent(value: string, tagName: string) {
  const pattern = new RegExp(`<${tagName}>\\s*([\\s\\S]*?)\\s*<\\/${tagName}>`);
  return value.match(pattern)?.[1]?.trim();
}

function replaceTaggedContent(value: string, tagName: string, replacement: string) {
  const pattern = new RegExp(`(<${tagName}>)[\\s\\S]*?(<\\/${tagName}>)`);
  return value.replace(pattern, (_match, openTag: string, closeTag: string) =>
    `${openTag}\n${replacement}\n${closeTag}`);
}
